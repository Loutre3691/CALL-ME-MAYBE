"""Function call generation through constrained decoding of the LLM."""

from typing import Any
from llm_sdk import Small_LLM_Model  # type: ignore[attr-defined]
from src.parsing import ParsingInput, ParsingFunction
import numpy
import json
import os

MAX_NAME_TOKENS = 20
MAX_TOKENS = 100


def ft_vocab_inverse(vocab: dict[str, int]) -> dict[int, str]:
    """Invert the vocabulary: (token -> id) becomes (id -> token).

    Args:
        vocab: model vocabulary, maps each token to its id.

    Returns:
        The inverted dictionary, mapping each id to its token.
    """
    inverse: dict[int, str] = {}
    for key, value in vocab.items():
        inverse[value] = key
    return inverse


def create_text(input_text: ParsingInput,
                list_functions: list[ParsingFunction]) -> str:
    """Build the text sent to the LLM for a given question.

    The text contains the list of available functions (name and
    description), the question, then the "Function to call: " primer.

    Args:
        input_text: the user's prompt.
        list_functions: the functions the LLM can choose from.

    Returns:
        The full text to encode.
    """
    prompt = "\nQuestion: " + input_text.prompt
    funct_desc = []
    funct_desc.append("Functions: ")
    for f in list_functions:
        funct_desc.append(f"- {f.name}: {f.description}")

    new_text = "\n".join(funct_desc)
    new_text = "\n".join([new_text, prompt, "Function to call: "])
    return new_text


def rules_name_function(candidat: str, functions: list[str]) -> bool:
    """Tell whether the candidate can still become a function name.

    Args:
        candidat: name prefix generated so far (tested token included).
        functions: allowed function names.

    Returns:
        True if at least one function name starts with the candidate.
    """
    return any(function.startswith(candidat) for function in functions)


def rules_number_parameters(text: str) -> bool:
    """Tell whether the text can be the start of a valid JSON number.

    Only the characters "0123456789.-}," are accepted. The text must
    not start with a dot, contain two dots, or have a "-" anywhere
    but at the start. The "," and "}" characters end the number and
    require at least one digit before them.

    Args:
        text: numeric value generated so far (tested token included).

    Returns:
        True if the text is allowed, False otherwise.
    """
    for c in text:
        if c not in "0123456789.-}," or text[0] == "." or text.count(".") > 1:
            return False
        if "-" in text[1:]:
            return False

    number = text.rstrip(",}")

    if "," in number or "}" in number:
        return False

    if number != text and not any(c.isdigit() for c in number):
        return False
    return True


def create_list_json(result: dict[str, Any], list_json: list[dict[str, Any]],
                     generated: str, prompt: ParsingInput) -> dict[str, Any]:
    """Build the output JSON entry for a prompt.

    Args:
        result: parameters generated by the LLM.
        list_json: results accumulated so far (unused here).
        generated: name of the chosen function.
        prompt: the original prompt.

    Returns:
        A dict with the keys "prompt", "name" and "parameters".
    """
    dict_json = {
        "prompt": prompt.prompt,
        "name": generated,
        "parameters": result
    }

    return dict_json


def is_finished(generated: str, mode: str) -> bool:
    """Tell whether the generated value is complete for its type.

    A string is finished as soon as a closing quote appears;
    a number as soon as a comma or a closing brace appears.

    Args:
        generated: value generated so far.
        mode: parameter type ("string" or "number").

    Returns:
        True if the value is finished.
    """
    if mode == "string":
        if '"' not in generated:
            return False

    elif mode == "number" or mode == "integer":
        if "}" not in generated and "," not in generated:
            return False
    return True


def constrained_decoding(model: Small_LLM_Model, token: list[int],
                         vocab_inverse: dict[int, str], generated: str,
                         functions: list[str], mode: str) -> int:
    """Pick the next token by masking the forbidden ones.

    The logits of tokens that break the rules of the mode are set
    to -inf, then the token with the highest logit is taken.

    Args:
        model: the language model.
        token: ids of all the tokens read by the model so far.
        vocab_inverse: inverted vocabulary (id -> text).
        generated: text already generated for the current value.
        functions: allowed function names ("name" mode).
        mode: "name", "number" or "string".

    Returns:
        The id of the next token to append.
    """
    # the LLM reads the whole list of ids and gives a score
    # to every possible token of the vocabulary
    logits = model.get_logits_from_input_ids(token)

    for pos in range(len(logits)):
        # .get avoids an edge case when the logits id is above the
        # number of ids in the LLM vocab: it creates a "" that will be
        # set to -inf right after
        text_vocab = vocab_inverse.get(pos, "")

        if mode == "string":
            rule = True
        elif mode == "number" or mode == "integer":
            rule = rules_number_parameters((generated + text_vocab))
        else:
            rule = rules_name_function((generated + text_vocab), functions)

        # set -inf on every score whose token does not match the rules
        # for the current prompt + function text
        if text_vocab == "" or not rule:
            logits[pos] = -numpy.inf

    # argmax finds the position of the max logit among the tokens
    # next_id holds the id of the max logit
    next_id = int(numpy.argmax(logits))
    return next_id


def write_parameter(parameters: dict[str, Any], token: list[int],
                    vocab_inverse: dict[int, str], model: Small_LLM_Model,
                    functions: list[str], visualizer: bool) -> dict[str, Any]:
    """Generate the parameter values of a function, one by one.

    Write the JSON key by key, then let the LLM generate each
    value under constraint (string or number).

    Args:
        parameters: function parameters (name -> type).
        token: ids read by the model (modified in place).
        vocab_inverse: inverted vocabulary (id -> text).
        model: the language model.
        functions: allowed function names.
        visualizer: if True, display the generation live.

    Returns:
        The generated parameters (name -> value).
    """
    result: dict[str, Any] = {}
    generated = ""
    for key, value in parameters.items():
        mode = value.type
        # write the JSON code
        if not result:
            text = '{"' + key + '":'
        elif generated.endswith(","):
            text = '"' + key + '":'
        else:
            text = ',"' + key + '":'

        if mode == "string":
            text += '"'

        # the text becomes tokens, then extend adds them to what\
        #  the model reads
        token.extend(model.encode(text).tolist()[0])

        generated = ""
        nbr_tour = 0
        if visualizer:
            print(text, end="", flush=True)
        while (nbr_tour < MAX_TOKENS and not is_finished(generated, mode)):
            next_id = constrained_decoding(model, token, vocab_inverse,
                                           generated, functions, mode)
            nbr_tour += 1
            token.append(next_id)
            token_str = model.decode(next_id)
            if visualizer:
                print(token_str, end="", flush=True)

            generated = generated + token_str

            if mode == "string":
                new = generated.split('"')[0]
            else:
                new = generated.rstrip('",}')

        if mode == "string":
            try:
                # json.loads() handles the backslashes in the
                # regex output with decimals \d+
                new = json.loads('"' + new + '"')
            except json.JSONDecodeError:
                print("Error: json text not valid")

        # store the value
        result[key] = new

        if mode == "number":
            try:
                result[key] = float(new)
            except ValueError:
                result[key] = 0.0
                print(f"Error: Convert {new} in int not possible")
                continue
        elif mode == "integer":
            try:
                result[key] = int(new)
            except ValueError:
                result[key] = 0
                print(f"Error: Convert {new} in int not possible")
                continue
    return result


def transorm_text_in_numero(list_input: list[ParsingInput],
                            list_functions: list[ParsingFunction],
                            output_path: str, visualizer: bool) -> None:
    """Transform each prompt into a function call and write it as JSON.

    For each prompt: the text is encoded into ids, the LLM chooses the
    function name then its parameters (constrained decoding), and the
    result is saved in the output file.

    Args:
        list_input: prompts to process.
        list_functions: available functions.
        output_path: path of the output JSON (directories created if needed).
        visualizer: if True, display the generation live.
    """
    # 1. encode    : the question becomes a list of ids
    #                 "Reverse the string..." → [45695, 279, 914, ...]
    #  2. LLM       : it reads the whole list and gives a score
    #                 to every token of the vocabulary (~150,000 scores)
    #  3. argmax    : the position of the max score
    #                 = the id of the most likely next token
    #  4. append    : add this id at the end of the list
    #  5. repeat from step 2 with the longer list
    functions = []
    for f in list_functions:
        functions.append(f.name)

    if not functions:
        print("Error: prompt functions_definitions is empty")
        exit(1)

    try:
        model = Small_LLM_Model()
        path_vocab = model.get_path_to_vocab_file()

        with open(path_vocab) as file:
            vocab = json.load(file)

        vocab_inverse = ft_vocab_inverse(vocab)

    except Exception as e:
        print(f"Error: {e}")
        exit(1)

    for id, vocab in vocab_inverse.items():
        vocab_inverse[id] = vocab.replace("Ġ", " ")

    list_json: list[dict[str, Any]] = []
    for prompt in list_input:
        text_functions = create_text(prompt, list_functions)

        tokens = model.encode(text_functions)
        # tolist converts the array into a list
        tokens = tokens.tolist()
        # tokens[0] gets the inner list containing all the ids
        # of the sentence
        token = tokens[0]

        generated = ""

        nbr_tour = 0
        if visualizer:
            print()
            print(prompt.prompt)
        while generated not in functions and nbr_tour < MAX_NAME_TOKENS:
            next_id = constrained_decoding(model, token, vocab_inverse,
                                           generated, functions, "name")
            nbr_tour += 1
            token.append(next_id)
            token_str = model.decode(next_id)
            generated = generated + token_str
            # print flush=True forces immediate output
            if visualizer:
                print(token_str, end="", flush=True)

        if generated not in functions:
            print(f"Error: {generated} is not in functions list")
            continue

        for f in list_functions:
            if generated == f.name:
                result = write_parameter(f.parameters, token, vocab_inverse,
                                         model, functions, visualizer)

        list_json.append(create_list_json(result, list_json, generated,
                                          prompt))

    try:
        # os.makedirs -> create directory data/output
        directory = os.path.dirname(output_path)
        if directory:
            os.makedirs(directory, exist_ok=True)
        with open(output_path, "w") as file:
            json.dump(list_json, file, indent=4, ensure_ascii=False)
    # OSError atrape filenotfounderror permissionerror et
    # isadirectoryerror ensemble
    except OSError as e:
        print(f"Error: {e} problem")
        exit(1)
